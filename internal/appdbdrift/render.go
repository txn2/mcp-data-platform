// Tx is a READ ONLY transaction the catalog is read in: the postgres
// toolkit's.
type Tx interface {
	Query(ctx context.Context, s postgres.Statement) (*postgres.Result, error)
	Rollback()
}

// Reader opens a READ ONLY transaction on an application database.
type Reader interface {
	ReadTx(ctx context.Context, connection string) (Tx, error)
}

// Toolkit is the postgres toolkit as a Reader.
type Toolkit struct{ *postgres.Toolkit }

// ReadTx implements Reader.
func (t Toolkit) ReadTx(ctx context.Context, connection string) (Tx, error) {
	tx, err := t.Begin(ctx, postgres.TxOptions{Connection: connection, ReadOnly: true})
	if err != nil {
		return nil, err //nolint:wrapcheck // the toolkit's value-free summary is the text
	}
	return tx, nil
}

// Unsupported is an object an adopted baseline cannot write, which refuses the
// adoption: writing a baseline without it would describe a schema the
// database does not hold.
type Unsupported struct {
	Kind string `json:"kind"`
	Name string `json:"name"`
}

// ErrTooLarge refuses a schema one of whose sections has more objects than a
// statement on the connection may return (its max_rows).
var ErrTooLarge = errors.New("the schema has more objects of one kind than the connection's max_rows; raise max_rows to adopt it")

// notExtension leaves out an object an extension owns: CREATE EXTENSION makes
// it.
const notExtension = `NOT EXISTS (SELECT 1 FROM pg_depend dep WHERE dep.objid = %s AND dep.deptype = 'e')`

func ext(col string) string { return fmt.Sprintf(notExtension, col) }

