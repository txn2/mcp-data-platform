// functionsSQL is the schema's functions and procedures whose body is SQL
// standard (BEGIN ATOMIC, checked against the tables when created), or every
// other one.
func functionsSQL(standardBody bool) string {
	cond := "p.prosqlbody IS NULL"
	if standardBody {
		cond = "p.prosqlbody IS NOT NULL"
	}
	return `SELECT rtrim(pg_get_functiondef(p.oid)) || ';' AS ddl
FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = $1 AND p.prokind IN ('f', 'p') AND ` + cond + ` AND ` + ext("p.oid") + ` ORDER BY p.oid`
}

// unsupportedSQL lists the objects of a schema a baseline does not write.
var unsupportedSQL = `SELECT kind, name FROM (
 SELECT 'aggregate or window function' AS kind, p.proname::text AS name FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = $1 AND p.prokind IN ('a', 'w') AND ` + ext("p.oid") + `
 UNION ALL SELECT 'composite type', t.typname::text FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
   JOIN pg_class c ON c.oid = t.typrelid WHERE n.nspname = $1 AND c.relkind = 'c' AND ` + ext("t.oid") + `
 UNION ALL SELECT 'range type', t.typname::text FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
   WHERE n.nspname = $1 AND t.typtype = 'r' AND ` + ext("t.oid") + `
 UNION ALL SELECT 'foreign table', c.relname::text FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = $1 AND c.relkind = 'f'
 UNION ALL SELECT 'table inheritance', c.relname::text FROM pg_inherits h JOIN pg_class c ON c.oid = h.inhrelid
   JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = $1 AND NOT c.relispartition AND c.relkind IN ('r', 'p')
 UNION ALL SELECT 'rule', r.rulename::text FROM pg_rewrite r JOIN pg_class c ON c.oid = r.ev_class
   JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = $1 AND r.rulename <> '_RETURN'
 UNION ALL SELECT 'operator', o.oprname::text FROM pg_operator o JOIN pg_namespace n ON n.oid = o.oprnamespace
   WHERE n.nspname = $1 AND ` + ext("o.oid") + `
 UNION ALL SELECT 'collation', co.collname::text FROM pg_collation co JOIN pg_namespace n ON n.oid = co.collnamespace
   WHERE n.nspname = $1 AND ` + ext("co.oid") + `
 UNION ALL SELECT 'statistics object', s.stxname::text FROM pg_statistic_ext s JOIN pg_namespace n ON n.oid = s.stxnamespace
   WHERE n.nspname = $1
 UNION ALL SELECT 'text search configuration', cfg.cfgname::text FROM pg_ts_config cfg JOIN pg_namespace n ON n.oid = cfg.cfgnamespace
   WHERE n.nspname = $1 AND ` + ext("cfg.oid") + `
) x ORDER BY 1, 2`

// baselineHeader opens every baseline. Function bodies are checked when they
// run, not when the baseline creates them before the tables they read, as
// pg_dump does.
const baselineHeader = "-- Baseline adopted from the schema the database held (#2406).\nSET LOCAL check_function_bodies = off;\n"

// Render reads schema's objects and writes the DDL that builds them from
// zero, every name schema-qualified. Objects it cannot write are returned
// instead, and refuse the adoption.
func Render(ctx context.Context, kit Reader, connection, schema string) (string, []Unsupported, error) {
	tx, err := kit.ReadTx(ctx, connection)
	if err != nil {
		return "", nil, err //nolint:wrapcheck // the toolkit's value-free summary is the text
	}
	defer tx.Rollback()
	// With only pg_catalog on the path, format_type and the pg_get_*def
	// functions qualify every name the schema's objects refer to.
	if _, err := tx.Query(ctx, postgres.Statement{
		Connection: connection,
		SQL:        "SELECT set_config('search_path', 'pg_catalog', true)",
	}); err != nil {
		return "", nil, err //nolint:wrapcheck // the toolkit's value-free summary is the text
	}
	unsupported, err := readUnsupported(ctx, tx, connection, schema)
	if err != nil || len(unsupported) > 0 {
		return "", unsupported, err
	}
	up, err := renderDDL(ctx, tx, connection, schema)
	return up, unsupported, err
}

// readUnsupported lists the objects of schema a baseline does not write.
func readUnsupported(ctx context.Context, tx Tx, connection, schema string) ([]Unsupported, error) {
	res, err := tx.Query(ctx, postgres.Statement{Connection: connection, SQL: unsupportedSQL, Params: []any{schema}})
	if err != nil {
		return nil, err //nolint:wrapcheck // the toolkit's value-free summary is the text
	}
	out := []Unsupported{}
	for _, r := range res.Rows {
		if len(r) < 2 {
			continue
		}
		k, _ := r[0].(string)
		n, _ := r[1].(string)
		out = append(out, Unsupported{Kind: k, Name: n})
	}
	return out, nil
}

// renderDDL writes every section's DDL, in order, after the header.
func renderDDL(ctx context.Context, tx Tx, connection, schema string) (string, error) {
	var b strings.Builder
	_, _ = b.WriteString(baselineHeader)
	for _, sql := range renderSections {
		res, err := tx.Query(ctx, postgres.Statement{Connection: connection, SQL: sql, Params: []any{schema}})
		if err != nil {
			return "", err //nolint:wrapcheck // the toolkit's value-free summary is the text
		}
		if res.Truncated {
			return "", ErrTooLarge
		}
		for _, r := range res.Rows {
			if ddl, _ := firstText(r); ddl != "" {
				_, _ = b.WriteString(ddl)
				_ = b.WriteByte('\n')
			}
		}
	}
	return b.String(), nil
}

// firstText is a row's first column as text.
func firstText(r []any) (string, bool) {
	if len(r) == 0 {
		return "", false
	}
	s, ok := r[0].(string)
	return s, ok
}
