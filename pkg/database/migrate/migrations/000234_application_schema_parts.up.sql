-- 000234: an application's schema is a part, with a run role (#2539).
--
-- A schema is added to an application at any time, not only when it is
-- created. When it is added, the migration version already applied is kept
-- as schema_adopted_version: a release applies nothing already applied, and
-- a rollback never reverts a migration below it, which no release applied.
--
-- application_run_roles is the login role each application's scripts run
-- their statements as on the connection holding its schema. The platform
-- creates the role when the schema is added and drops it when the schema is
-- removed. Its password is generated by the platform, sealed with the
-- deployment's encryption key bound to the application, connection, schema
-- and role, and never returned by any route or tool.
ALTER TABLE applications ADD COLUMN IF NOT EXISTS schema_adopted_version INT NOT NULL DEFAULT 0;
ALTER TABLE applications ADD COLUMN IF NOT EXISTS schema_added_by TEXT NOT NULL DEFAULT '';
ALTER TABLE applications ADD COLUMN IF NOT EXISTS schema_added_at TIMESTAMPTZ;

UPDATE applications SET schema_added_by = created_by, schema_added_at = created_at
 WHERE connection <> '' AND schema_added_at IS NULL;

CREATE TABLE IF NOT EXISTS application_run_roles (
    application_id  TEXT        PRIMARY KEY REFERENCES applications (id) ON DELETE CASCADE,
    connection      TEXT        NOT NULL,
    schema_name     TEXT        NOT NULL,
    role_name       TEXT        NOT NULL,
    password_sealed TEXT        NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (connection, role_name)
);
