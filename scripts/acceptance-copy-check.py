#!/usr/bin/env python3
"""acceptance-copy-check.py -- fail when a diff removes text from production
Go that an acceptance criterion still asserts (#2519).

#2498 changed the endpoint binding refusal from "only an administrator can
bind a script to an endpoint" to refusals that name the case, and updated the
unit test that asserted the old text. test/acceptance/issue_2171_test.go still
asserted strings.Contains(refusal, "only an administrator"). make
acceptance-check runs only the criteria in acceptance files a diff changes,
and the whole suite runs only in the E2E Nightly, so the stale criterion was
found by the nightly after merge and refused the v1.153.2 tag.

The check reads the diff against the merge base with main. For every changed
production Go file under pkg/, internal/ or cmd/ (not a _test.go file, not a
generated file), it collects the string literals outside import declarations
of the base and working versions, adjacent literals joined by + read as one.
A text is removed when the changed files hold it fewer times after the diff
than before.

It then reads the string literals of every Go file under test/acceptance and
fails on a literal that matches a removed text:

  - equal to it, when no production Go file holds the text any longer (a
    string moved between files is not removed);
  - inside it (a criterion asserts a message with strings.Contains; a fragment
    holds a space and at least MIN_FRAGMENT characters), when fewer production
    literals hold the fragment after the diff than before, and either none
    holds it any longer or the criterion line and the removed literal were
    written in the same commit. "only an administrator" still appears in the
    owner-transfer refusal, so only the second rule finds #2498: issue 2171's
    criterion and the refusal it read were both written by 725f9b4af. A
    fragment as common as "knowledge page" loses one of its places to many
    diffs without a criterion reading that place.

Each finding names the acceptance file and line and the production file the
text left. A criterion line the diff itself changed is the author's update and
is not reported. A base branch that cannot be resolved fails.
"""

from __future__ import annotations

import bisect
import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PRODUCTION_DIRS = ("pkg/", "internal/", "cmd/")
ACCEPTANCE_DIR = "test/acceptance/"
MIN_FRAGMENT = 8
LETTER = re.compile(r"[A-Za-z]")
ESCAPES = {"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\", "'": "'"}
UNCOMMITTED = "0" * 40

# The marker go generate writes (https://go.dev/s/generatedcode), in the forms
# generators spell it (swag: "// Package apidocs Code generated by
# swaggo/swag. DO NOT EDIT"). A generated file's literals are its generator's
# output, never a message a criterion reads.
GENERATED = re.compile(r"^//.*Code generated .*DO NOT EDIT", re.MULTILINE)
# An import declaration, grouped or single. Its paths are not messages.
IMPORTS = re.compile(r"^import\s*(?:\([^)]*\)|[^\n]*)", re.MULTILINE)
# One Go token the scan cares about: a comment, an interpreted or raw string,
# a rune literal, a +, or any other run of non-space characters.
TOKEN = re.compile(
    r"//[^\n]*|/\*.*?\*/"
    r'|"((?:\\.|[^"\\\n])*)"'
    r"|`([^`]*)`"
    r"|'(?:\\.|[^'\\\n])*'"
    r"|(\+)"
    r"|[^\s\"`'/+]+|/",
    re.DOTALL,
)

# A line that asserts text is present: a negated strings test (if
# !strings.Contains(got, want) { fail }), a testify Contains/Equal, or a != to
# a literal. strings.Contains without the ! in an if asserts the text is
# ABSENT (#2428 asserts "postgres_query" is listed nowhere), and a removal
# cannot break that.
POSITIVE = re.compile(
    r"!\s*strings\.(?:Contains|HasPrefix|HasSuffix|EqualFold)\("
    r"|\b(?:assert|require)\.(?:Contains|Equal|EqualValues)\("
    r'|!=\s*"'
)

Literal = tuple[str, str, int]  # text, file, line


def git(*args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", *args], cwd=REPO_ROOT, check=check, capture_output=True, text=True)


def merge_base(base_branch: str) -> str:
    for ref in (f"origin/{base_branch}", base_branch):
        if git("rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}", check=False).returncode == 0:
            return git("merge-base", "HEAD", ref).stdout.strip()
    raise SystemExit(
        f"FAIL acceptance-copy-check: cannot resolve base branch '{base_branch}' "
        f"(tried origin/{base_branch} and {base_branch}); fetch it or set BASE_BRANCH."
    )


def changed_files(base: str) -> list[str]:
    """Committed, staged, unstaged, untracked and deleted paths."""
    names = set(git("diff", "--name-only", base).stdout.splitlines())
    names.update(git("ls-files", "--others", "--exclude-standard").stdout.splitlines())
    return sorted(n for n in names if n)


def is_production(rel: str) -> bool:
    return rel.startswith(PRODUCTION_DIRS) and rel.endswith(".go") and not rel.endswith("_test.go")


def base_text(base: str, rel: str) -> str:
    shown = git("show", f"{base}:{rel}", check=False)
    return shown.stdout if shown.returncode == 0 else ""


def work_text(rel: str) -> str:
    path = REPO_ROOT / rel
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def unescape(body: str) -> str:
    return re.sub(r"\\(.)", lambda m: ESCAPES.get(m.group(1), m.group(0)), body)


def shorten(text: str, limit: int = 160) -> str:
    one = " ".join(text.split())
    return one if len(one) <= limit else one[: limit - 3] + "..."


def blank_imports(src: str) -> str:
    """src with its import declarations blanked, newlines kept so lines hold."""
    return IMPORTS.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), src)


def literals(src: str):
    """Yield (line, text) for each string literal in Go source outside import
    declarations, a run of literals joined by + yielded once as their
    concatenation. Comments and rune literals are skipped."""
    src = blank_imports(src)
    breaks = [i for i, c in enumerate(src) if c == "\n"]
    pending: list[str] = []
    pending_at = 0
    joinable = False
    for m in TOKEN.finditer(src):
        token = m.group(0)
        if token.startswith(("//", "/*")):
            continue
        interpreted, raw, plus = m.group(1), m.group(2), m.group(3)
        if interpreted is not None or raw is not None:
            text = unescape(interpreted) if interpreted is not None else raw
            if pending and joinable:
                pending.append(text)
            else:
                if pending:
                    yield bisect.bisect_left(breaks, pending_at) + 1, "".join(pending)
                pending, pending_at = [text], m.start()
            joinable = False
        elif plus and pending:
            joinable = True
        else:
            if pending:
                yield bisect.bisect_left(breaks, pending_at) + 1, "".join(pending)
            pending, joinable = [], False
    if pending:
        yield bisect.bisect_left(breaks, pending_at) + 1, "".join(pending)


def wordy(text: str) -> bool:
    return len(text) >= 2 and LETTER.search(text) is not None


def production_literals(src: str, rel: str) -> list[Literal]:
    if GENERATED.search(src):
        return []
    return [(text, rel, line) for line, text in literals(src) if wordy(text)]


def changed_literals(base: str, files: list[str]) -> tuple[list[Literal], list[Literal]]:
    """The literals of the changed production files before and after the diff.
    A file the diff did not change holds the same literals on both sides, so
    only these can move a count."""
    before: list[Literal] = []
    after: list[Literal] = []
    for rel in files:
        if is_production(rel):
            before += production_literals(base_text(base, rel), rel)
            after += production_literals(work_text(rel), rel)
    return before, after


def removed_texts(before: list[Literal], after: list[Literal]) -> dict[str, Literal]:
    """Each text the changed files hold fewer times after the diff, mapped to
    the first base literal that held it."""
    lost = Counter(t for t, _, _ in before)
    lost.subtract(Counter(t for t, _, _ in after))
    removed: dict[str, Literal] = {}
    for lit in before:
        if lost[lit[0]] > 0:
            removed.setdefault(lit[0], lit)
    return removed


def held_anywhere(literal: str, exact: bool) -> bool:
    """Whether a production Go file holds literal now: as a whole literal when
    exact, inside one otherwise. git grep narrows the files to those holding
    the literal's longest plain run, and only those are read."""
    runs = [r for r in re.split(r"[\\\"`\n\t\r]", literal) if r]
    if not runs:
        return False
    probe = max(runs, key=len)[:80]
    files = set(git("grep", "-l", "-F", "-e", probe, "--", *PRODUCTION_DIRS, check=False).stdout.splitlines())
    files.update(
        f for f in git("ls-files", "--others", "--exclude-standard", *PRODUCTION_DIRS).stdout.splitlines()
        if probe in work_text(f)
    )
    for rel in files:
        if not is_production(rel):
            continue
        for text, _, _ in production_literals(work_text(rel), rel):
            if (text == literal) if exact else (literal in text):
                return True
    return False


def blamed(rev: str | None, rel: str, line: int) -> str:
    """The commit that wrote a line, at rev or in the working tree."""
    args = ["blame", "-l", "-s", "-L", f"{line},{line}"]
    if rev:
        args.append(rev)
    out = git(*args, "--", rel, check=False).stdout
    return out.split()[0].lstrip("^") if out.strip() else ""


def acceptance_files() -> list[str]:
    listed = git("ls-files", ACCEPTANCE_DIR).stdout.splitlines()
    listed += git("ls-files", "--others", "--exclude-standard", ACCEPTANCE_DIR).stdout.splitlines()
    return sorted({f for f in listed if f.endswith(".go") and not Path(f).name.startswith("NOTES_")})


def added_lines(base: str) -> dict[str, set[int] | None]:
    """The acceptance lines the diff adds, by file; None for a file the diff
    adds whole. A criterion the diff writes is the author's update, and
    make acceptance-check already requires a passing run of it."""
    added: dict[str, set[int] | None] = {
        f: None for f in git("ls-files", "--others", "--exclude-standard", ACCEPTANCE_DIR).stdout.splitlines()
    }
    current = ""
    for row in git("diff", "-U0", base, "--", ACCEPTANCE_DIR).stdout.splitlines():
        if row.startswith("+++ "):
            current = row[6:] if row.startswith("+++ b/") else ""
            if current and git("cat-file", "-e", f"{base}:{current}", check=False).returncode != 0:
                added[current] = None
        elif row.startswith("@@") and current and added.get(current, set()) is not None:
            hunk = re.search(r"\+(\d+)(?:,(\d+))?", row)
            start, count = int(hunk.group(1)), int(hunk.group(2) or 1)
            added.setdefault(current, set()).update(range(start, start + count))
    return added


def is_fragment(literal: str, text: str) -> bool:
    return literal != text and " " in literal and len(literal) >= MIN_FRAGMENT and literal in text


class Judge:
    """Decides, once per literal, whether a match against a removed text is a
    stale criterion."""

    def __init__(self, base: str, before: list[Literal], after: list[Literal]) -> None:
        self.base, self.before, self.after = base, before, after
        self.exact_gone: dict[str, bool] = {}
        self.dropped: dict[str, bool] = {}
        self.fragment_gone: dict[str, bool] = {}

    def exact(self, literal: str) -> bool:
        if literal not in self.exact_gone:
            self.exact_gone[literal] = not held_anywhere(literal, exact=True)
        return self.exact_gone[literal]

    def fragment(self, literal: str, criterion: tuple[str, int], source: Literal) -> bool:
        if literal not in self.dropped:
            held_before = sum(literal in t for t, _, _ in self.before)
            held_after = sum(literal in t for t, _, _ in self.after)
            self.dropped[literal] = held_after < held_before
        if not self.dropped[literal]:
            return False
        if literal not in self.fragment_gone:
            self.fragment_gone[literal] = not held_anywhere(literal, exact=False)
        if self.fragment_gone[literal]:
            return True
        written = blamed(None, *criterion)
        if not written or written == UNCOMMITTED:
            return False
        return written == blamed(self.base, source[1], source[2])


def findings(base: str, before: list[Literal], after: list[Literal]) -> list[str]:
    removed = removed_texts(before, after)
    judge = Judge(base, before, after)
    added = added_lines(base)
    out: list[str] = []
    for rel in acceptance_files():
        if rel in added and added[rel] is None:
            continue
        src = work_text(rel)
        lines = src.splitlines()
        for lineno, literal in literals(src):
            if not wordy(literal) or lineno in (added.get(rel) or ()):
                continue
            if lineno > len(lines) or not POSITIVE.search(lines[lineno - 1]):
                continue
            for text, source in removed.items():
                if literal == text:
                    stale = judge.exact(literal)
                elif is_fragment(literal, text):
                    stale = judge.fragment(literal, (rel, lineno), source)
                else:
                    continue
                if stale:
                    out.append(f'  {rel}:{lineno}: "{shorten(literal)}" matches "{shorten(text)}", which {source[1]} no longer has')
                    break
    return out


def main() -> int:
    base = merge_base(os.environ.get("BASE_BRANCH", "main"))
    before, after = changed_literals(base, changed_files(base))
    if not removed_texts(before, after):
        print("acceptance-copy-check: no text removed from production Go against main")
        return 0
    failed = findings(base, before, after)
    if not failed:
        print("acceptance-copy-check: text left production Go; no acceptance criterion asserts it")
        return 0
    print("FAIL acceptance-copy-check: an acceptance criterion asserts text this diff removed from production Go.", file=sys.stderr)
    print("The E2E Nightly would fail on each of these; update the criterion to what the platform says now:", file=sys.stderr)
    print("\n".join(failed), file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
