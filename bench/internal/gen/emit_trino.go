package gen

import (
	"fmt"
	"sort"
	"strings"
)

// insertChunk bounds rows per INSERT statement to keep statements parseable.
const insertChunk = 250

// TrinoSQL emits the warehouse DDL/DML for the memory catalog. Statements are
// idempotent (DROP + CREATE) so re-seeding a running stack is safe.
func (d *Dataset) TrinoSQL() string {
	var b strings.Builder
	b.WriteString("-- Generated by bench/seedgen (seed ")
	fmt.Fprintf(&b, "%d", Seed)
	b.WriteString("). Do not edit; regenerate with `make bench-gen`.\n")
	b.WriteString("CREATE SCHEMA IF NOT EXISTS memory.bench;\n\n")
	d.emitCustomersSQL(&b)
	d.emitOrdersSQL(&b)
	d.emitLegacyOrdersSQL(&b)
	d.emitDailyRevenueSQL(&b)
	return b.String()
}

// emitCustomersSQL writes the customer dimension.
func (d *Dataset) emitCustomersSQL(b *strings.Builder) {
	b.WriteString("DROP TABLE IF EXISTS memory.bench.customers;\n")
	b.WriteString("CREATE TABLE memory.bench.customers (\n" +
		"    customer_id INTEGER,\n    name VARCHAR,\n    region VARCHAR,\n    tier VARCHAR,\n    created_at TIMESTAMP\n);\n")
	rows := make([]string, len(d.Customers))
	for i, c := range d.Customers {
		rows[i] = fmt.Sprintf("(%d, '%s', '%s', '%s', TIMESTAMP '%s')",
			c.ID, sqlEscape(c.Name), c.Region, c.Tier, c.CreatedAt.Format("2006-01-02 15:04:05"))
	}
	writeInserts(b, "memory.bench.customers", rows)
}

// emitOrdersSQL writes the order fact. The amount and discount columns carry
// the units trap: plain INTEGER columns named without a unit suffix.
func (d *Dataset) emitOrdersSQL(b *strings.Builder) {
	b.WriteString("\nDROP TABLE IF EXISTS memory.bench.orders;\n")
	b.WriteString("CREATE TABLE memory.bench.orders (\n" +
		"    order_id INTEGER,\n    customer_id INTEGER,\n    order_ts TIMESTAMP,\n    status VARCHAR,\n    amount INTEGER,\n    discount INTEGER\n);\n")
	rows := make([]string, len(d.Orders))
	for i, o := range d.Orders {
		rows[i] = fmt.Sprintf("(%d, %d, TIMESTAMP '%s', '%s', %d, %d)",
			o.ID, o.CustomerID, o.TS.Format("2006-01-02 15:04:05"), o.Status, o.Amount, o.Discount)
	}
	writeInserts(b, "memory.bench.orders", rows)
}

// emitLegacyOrdersSQL writes the deprecated order table (the S1 deprecation
// distractor): an older projection of the first orders, totals in dollars.
func (d *Dataset) emitLegacyOrdersSQL(b *strings.Builder) {
	b.WriteString("\nDROP TABLE IF EXISTS memory.bench.legacy_orders;\n")
	b.WriteString("CREATE TABLE memory.bench.legacy_orders (\n" +
		"    order_id INTEGER,\n    customer_id INTEGER,\n    order_date DATE,\n    total DOUBLE\n);\n")
	rows := make([]string, 0, legacyCount)
	for _, o := range d.Orders[:legacyCount] {
		rows = append(rows, fmt.Sprintf("(%d, %d, DATE '%s', %.2f)",
			o.ID, o.CustomerID, o.TS.Format("2006-01-02"), float64(o.Amount)/100.0))
	}
	writeInserts(b, "memory.bench.legacy_orders", rows)
}

// emitDailyRevenueSQL writes the pre-aggregated index (an S1 discovery target
// and an S3 distractor: gross of discounts, so it cannot answer policy
// revenue questions).
func (d *Dataset) emitDailyRevenueSQL(b *strings.Builder) {
	b.WriteString("\nDROP TABLE IF EXISTS memory.bench.daily_region_revenue;\n")
	b.WriteString("CREATE TABLE memory.bench.daily_region_revenue (\n" +
		"    day DATE,\n    region VARCHAR,\n    gross_revenue_usd DOUBLE\n);\n")
	byID := d.customerByID()
	type key struct {
		day    string
		region string
	}
	sums := map[key]int64{}
	for _, o := range d.Orders {
		if o.Status != "completed" {
			continue
		}
		sums[key{o.TS.Format("2006-01-02"), byID[o.CustomerID].Region}] += o.Amount
	}
	keys := make([]key, 0, len(sums))
	for k := range sums {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].day != keys[j].day {
			return keys[i].day < keys[j].day
		}
		return keys[i].region < keys[j].region
	})
	rows := make([]string, len(keys))
	for i, k := range keys {
		rows[i] = fmt.Sprintf("(DATE '%s', '%s', %.2f)", k.day, k.region, float64(sums[k])/100.0)
	}
	writeInserts(b, "memory.bench.daily_region_revenue", rows)
}

// writeInserts emits chunked INSERT statements.
func writeInserts(b *strings.Builder, table string, rows []string) {
	for start := 0; start < len(rows); start += insertChunk {
		end := min(start+insertChunk, len(rows))
		b.WriteString("INSERT INTO " + table + " VALUES\n")
		b.WriteString(strings.Join(rows[start:end], ",\n"))
		b.WriteString(";\n")
	}
}

// sqlEscape doubles single quotes for SQL string literals.
func sqlEscape(s string) string {
	return strings.ReplaceAll(s, "'", "''")
}
