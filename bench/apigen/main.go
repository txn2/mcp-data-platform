// Command apigen regenerates the API-connection study's committed
// artifacts (issue #1027): the OpenAPI specs at the three catalog-size
// tiers and the task set whose ground truths are computed from the seeded
// fixture state. A determinism test diffs a fresh regeneration against
// the committed files (the bench/seedgen pattern).
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"

	"github.com/txn2/mcp-data-platform/bench/internal/apigen"
	"github.com/txn2/mcp-data-platform/bench/internal/task"
)

func main() {
	specsDir := flag.String("specs-dir", "specs", "output directory for the tiered OpenAPI specs")
	tasksDir := flag.String("tasks-dir", "tasks-api", "output directory for the study task YAML")
	flag.Parse()
	if err := run(*specsDir, *tasksDir); err != nil {
		fmt.Fprintln(os.Stderr, "apigen:", err)
		os.Exit(1)
	}
}

// run generates the catalog and writes every artifact.
func run(specsDir, tasksDir string) error {
	c := apigen.BuildCatalog()
	for tier, name := range apigen.TierNames() {
		raw, err := c.SpecJSON(tier)
		if err != nil {
			return err
		}
		if err := writeFile(filepath.Join(specsDir, name+".json"), raw); err != nil {
			return err
		}
	}
	tasks := apigen.Tasks(apigen.GenerateState(c))
	if err := writeTasks(tasks, tasksDir); err != nil {
		return err
	}
	return writeSmoke(tasks, tasksDir)
}

// writeSmoke emits the deterministic playback script for the scripted
// adapter.
func writeSmoke(tasks []task.Task, dir string) error {
	raw, err := json.MarshalIndent(apigen.ScriptedSmoke(tasks), "", "  ")
	if err != nil {
		return fmt.Errorf("marshal smoke script: %w", err)
	}
	return writeFile(filepath.Join(dir, "scripted-smoke.json"), append(raw, '\n'))
}

// writeTasks emits one YAML file per task, with the generated-file header
// the committed task set carries.
func writeTasks(tasks []task.Task, dir string) error {
	for _, t := range tasks {
		raw, err := yaml.Marshal(t)
		if err != nil {
			return fmt.Errorf("marshal task %s: %w", t.ID, err)
		}
		header := "# Generated by bench/apigen; ground truth is computed from the seeded fixture state.\n# Do not edit; regenerate with `make bench-api-gen`.\n"
		if err := writeFile(filepath.Join(dir, t.ID+".yaml"), append([]byte(header), raw...)); err != nil {
			return err
		}
	}
	return nil
}

// writeFile writes one artifact, creating parent directories.
func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	if err := os.WriteFile(path, data, 0o644); err != nil { // #nosec G306 -- committed repo artifacts, not secrets
		return err
	}
	fmt.Println("wrote", path)
	return nil
}
