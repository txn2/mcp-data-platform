def arm_cost(manifest, attempts):
    inp, out = PRICING[manifest["model"]]
    return sum(
        a["input_tokens"] * inp + a["output_tokens"] * out
        + a.get("cache_read_tokens", 0) * inp * 0.1
        + a.get("cache_creation_tokens", 0) * inp * 1.25
        for a in attempts
    ) / 1e6


