"""Recompute every table in the knowledge-pollution report from committed run data.

Reads the run families under bench/results/knowledge-pollution/ and prints the
report's tables with Wilson 95% intervals and Newcombe hybrid-score difference
intervals. No network, no API key, stdlib only: the same contract the
knowledge-use toolchain honors (pk_tables.py). Run from anywhere:

    python3 bench/reports/knowledge-pollution/pollution_tables.py

Classification is fully deterministic (protocol section 7): a graded answer is
matched against the cell's fixture-computed discriminants within the grader
tolerance. The discriminant table below is the protocol section 5.1 matrix,
generated by `pollutionplant -mode table` and pinned against the committed
graders by `pollutionplant -mode check`.
"""
