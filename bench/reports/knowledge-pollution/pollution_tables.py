def separation_exceptions(family, name):
    """Count violations of the per-episode observation==correct separation.

    The mechanism claim is observation-based: every episode whose COUNT
    observation arrived answered correctly; every episode without the
    observation adopted. An attempted query whose result errored delivers no
    observation and is counted with the non-observing episodes."""
    _, attempts, dirpath = load_arm(family, name)
    by_attempt = {}
    for t in transcripts(dirpath):
        by_attempt[t["attempt"]] = orders_count_status(t)
    exceptions = 0
    for a in attempts:
        cls = classify(a["task_id"], a.get("got_value"))
        _, observed = by_attempt.get(a["attempt"], (False, False))
        if observed and cls != "correct":
            exceptions += 1
        if not observed and cls != "adopted":
            exceptions += 1
    return exceptions


def exact_separation(family, name):
    exceptions = separation_exceptions(family, name)
    print(f"  exact separation on {family}/{name}: exceptions {exceptions} (observed->correct, unobserved->adopted)")


